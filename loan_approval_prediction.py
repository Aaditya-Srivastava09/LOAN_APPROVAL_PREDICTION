# Random Forest with controls to prevent overfitting
rf = RandomForestClassifier(
    n_estimators=100,
    max_depth=10,        # limits how deep trees grow
    min_samples_split=5, # needs 5 samples to split
    min_samples_leaf=2,  # leaves need at least 2 samples
    random_state=42
)

rf.fit(X_train, y_train)

print("Train Accuracy:", accuracy_score(y_train, rf.predict(X_train)))
